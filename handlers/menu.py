# Обработчики разделов меню (прайс-листы)
from aiogram import Router, F
from aiogram.types import Message

router = Router()


@router.message(F.text == "📄 Курсовые")
async def show_courseworks(message: Message):
    """Прайс курсовых работ."""
    text = (
        "📄 <b>Курсовые работы</b>\n"
        "Направление: «Разработка веб и мультимедийных приложений»\n\n"
        "• Только документ — <b>1 000 ₽</b> (3–5 дней)\n"
        "• Документ + сайт — <b>2 500 ₽</b> (4–5 дней)\n"
        "• Документ + сайт + презентация — <b>3 500 ₽</b> (5 дней)\n\n"
        "Чтобы оформить — нажми «📩 Заказать»."
    )
    await message.answer(text)


