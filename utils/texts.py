def order_preview(category_title: str, task: str, deadline: str, discount: bool) -> str:
    text = (
        "<b>📋 Проверьте заявку перед отправкой</b>\n\n"
        f"<b>Категория:</b> {category_title}\n\n"
        f"<b>Задача:</b>\n<blockquote>{task}</blockquote>\n"
        f"<b>Срок:</b> {deadline}\n"
    )
    if discount:
        text += (
            f"\n🎁 <b>Применена скидка {REPEAT_DISCOUNT}%</b> "
            "за повторное обращение."
        )
    text += "\n\n<i>Всё верно? Подтвердите отправку.</i>"
    return text


