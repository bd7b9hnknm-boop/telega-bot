def admin_new_order(order_id: int, category: str, task: str, deadline: str,
                    user_link: str, user_id: int, repeat: int) -> str:
    repeat_line = (
        f"🔁 Повторное обращение ({repeat} завершённых)\n" if repeat > 0 else ""
    )
    return (
        f"🔔 <b>Новая заявка №{order_id}</b>\n\n"
        f"<b>Категория:</b> {category}\n"
        f"<b>Задача:</b>\n<blockquote>{task}</blockquote>\n"
        f"<b>Срок:</b> {deadline}\n\n"
        f"{repeat_line}"
        f"👤 Клиент: {user_link}\n"
        f"🆔 <code>{user_id}</code>"
    )


