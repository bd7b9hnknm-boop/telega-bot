def render_category(key: str) -> str:
    """Сформировать HTML-описание категории для сообщения."""
    cat = CATALOG[key]
    lines = [f"<b>{cat['title']}</b>", "", f"<i>{cat['intro']}</i>", ""]
    for item in cat["items"]:
        lines.append(
            f"▸ <b>{item['name']}</b>\n"
            f"   💰 {item['price']}   •   ⏱ {item['term']}"
        )
        lines.append("")
    lines.append("<blockquote>Чтобы оставить заявку — нажмите кнопку ниже.</blockquote>")
    return "\n".join(lines)


def category_title(key: str) -> str:
    return CATALOG[key]["title"]
